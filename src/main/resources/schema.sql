CREATE TABLE IF NOT EXISTS customers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, email VARCHAR(160) NOT NULL UNIQUE, phone VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS assets (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_id BIGINT NOT NULL REFERENCES customers(id),
 name VARCHAR(100) NOT NULL, serial VARCHAR(80) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS parts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL, sku VARCHAR(40) NOT NULL UNIQUE,
 price DECIMAL(12,2) NOT NULL CHECK(price >= 0),
 stock INT NOT NULL CHECK(stock >= 0), minimum INT NOT NULL CHECK(minimum >= 0)
);
CREATE TABLE IF NOT EXISTS work_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 asset_id BIGINT NOT NULL REFERENCES assets(id),
 title VARCHAR(140) NOT NULL, description VARCHAR(2000) NOT NULL,
 priority VARCHAR(12) NOT NULL CHECK(priority IN ('LOW','NORMAL','HIGH')),
 status VARCHAR(20) NOT NULL CHECK(status IN ('DRAFT','APPROVED','IN_PROGRESS','COMPLETED','CANCELED')),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 due_date DATE NOT NULL,
 completed_at TIMESTAMP,
 resolution VARCHAR(2000) NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES work_orders(id),
 part_id BIGINT REFERENCES parts(id),
 description VARCHAR(160) NOT NULL,
 quantity INT NOT NULL CHECK(quantity BETWEEN 1 AND 1000),
 unit_price DECIMAL(12,2) NOT NULL CHECK(unit_price >= 0)
);
CREATE TABLE IF NOT EXISTS order_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 order_id BIGINT NOT NULL REFERENCES work_orders(id),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 message VARCHAR(2200) NOT NULL
);
CREATE TABLE IF NOT EXISTS stock_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 part_id BIGINT NOT NULL REFERENCES parts(id),
 order_id BIGINT REFERENCES work_orders(id),
 delta INT NOT NULL,
 reason VARCHAR(160) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_orders_status ON work_orders(status);
CREATE INDEX IF NOT EXISTS idx_items_order ON order_items(order_id);
CREATE INDEX IF NOT EXISTS idx_events_order ON order_events(order_id);
